import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const base = process.env.MINIAPP_TEST_URL || 'http://127.0.0.1:5173/app/'
const shots = path.resolve('shots')
await mkdir(shots, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome' })
const failures = []
const passed = []
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, locale: 'ru-RU' })
const page = await context.newPage()
page.on('pageerror', error => failures.push(error.message))
async function screenshot(name) {
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(document.getAnimations().filter(animation => animation.effect?.getTiming().iterations !== Infinity)
      .map(animation => animation.finished.catch(() => {})))
  })
  await page.screenshot({ path: path.join(shots, name + '.png'), fullPage: true })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  assert.ok(overflow <= 1, name + ': horizontal overflow ' + overflow)
}
async function ready() {
  await page.getByRole('heading', { name: 'Мои материалы' }).waitFor()
  await page.locator('.mx-file-row').first().waitFor()
}
try {
  await page.goto(base + '?demo=1')
  await ready()
  assert.equal(await page.locator('.mx-file-row').count(), 6)
  await screenshot('desktop-files')
  await page.getByRole('searchbox', { name: 'Поиск материалов' }).fill('Ньютона')
  assert.equal(await page.locator('.mx-file-row').count(), 1)
  await page.getByRole('searchbox', { name: 'Поиск материалов' }).fill('')
  await page.getByRole('button', { name: 'Презентации', exact: true }).click()
  assert.equal(await page.locator('.mx-file-row').count(), 1)
  await page.getByRole('button', { name: /Все материалы/ }).click()
  passed.push('Search and format filters')
  await page.getByRole('button', { name: 'Митоз и мейоз.pptx', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('heading', { name: 'Митоз и мейоз', exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Читать весь текст' }).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  passed.push('Keyboard selection and text preview dialog')
  await page.getByRole('button', { name: 'Удалить материал', exact: true }).click()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  assert.equal(await page.locator('.mx-file-row').count(), 6)
  await page.getByRole('button', { name: 'Удалить материал', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить', exact: true }).click()
  assert.equal(await page.locator('.mx-file-row').count(), 5)
  passed.push('Deletion requires confirmation and updates list')
  await page.locator('.mx-sidebar').getByRole('button', { name: 'Настройки', exact: true }).click()
  await page.getByLabel('Адрес API', { exact: true }).fill('https://example.test/v1')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Сохранить', exact: true }).isDisabled(), true)
  await page.getByRole('tab', { name: 'Распознавание' }).click()
  const toggle = page.getByRole('switch', { name: 'OCR сканов и рукописи' })
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-checked'), 'false')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await screenshot('desktop-ocr')
  await page.getByRole('tab', { name: 'Дополнительно' }).click()
  await page.getByLabel('Параллельных запросов', { exact: true }).selectOption('5')
  await page.locator('.mx-sidebar').getByRole('button', { name: 'Материалы', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button', { name: 'Остаться', exact: true }).click()
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await page.getByRole('tab', { name: 'Подключение', exact: true }).click()
  await screenshot('desktop-settings')
  passed.push('Settings save, OCR switch, advanced fields and unsaved changes guard')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '?demo=1')
  await ready()
  await screenshot('mobile-files')
  await page.getByRole('button', { name: 'Клетка и её органоиды.pdf', exact: true }).click()
  await page.locator('.mx-library--detail').waitFor()
  await screenshot('mobile-detail')
  for (const name of ['Создать тест', 'Конспект', 'Карточки', 'Читать весь текст']) {
    const label = page.getByRole('button', { name, exact: true }).locator('.ss-button__label')
    const visibleWidth = await label.evaluate(element => {
      const clip = element.querySelector('.ss-roll__mid')
      const text = element.querySelector('[data-live]')
      return !!clip && !!text && clip.getBoundingClientRect().width >= text.getBoundingClientRect().width - 1
    })
    assert.ok(visibleWidth, 'Mobile action label is clipped: ' + name)
  }
  await page.getByRole('button', { name: 'Читать весь текст' }).click()
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.locator('.mx-bottom-nav').getByRole('button', { name: 'Настройки', exact: true }).click()
  await screenshot('mobile-settings')
  passed.push('390px mobile list, detail, text dialog and settings')
  await page.setViewportSize({ width: 358, height: 800 })
  await page.goto(base + '?demo=1')
  await ready()
  await screenshot('mobile-358')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await screenshot('mobile-reduced-motion')
  passed.push('358px layout and reduced motion')
  await page.goto(base + '?demo=1&role=student')
  await ready()
  assert.equal(await page.getByRole('button', { name: 'Настройки', exact: true }).count(), 0)
  passed.push('Student navigation hides administration')
  await page.route('**/api/**', route => route.fulfill({ status: 401, contentType: 'application/json',
    body: JSON.stringify({ detail: 'Откройте мини-приложение из чата с ботом в MAX.' }) }))
  await page.goto(base)
  await page.getByRole('heading', { name: 'Открой локальную ссылку', exact: true }).waitFor()
  await screenshot('signed-out')
  assert.equal(await page.locator('.mx-file-row').count(), 0)
  passed.push('Unsigned visitors see no user data')
  assert.deepEqual(failures, [], 'Browser errors')
  await writeFile(path.join(shots, 'ui-results.json'), JSON.stringify({ passed, browserErrors: failures }, null, 2))
  console.log(JSON.stringify({ passed, browserErrors: failures }, null, 2))
} finally {
  await browser.close()
}
